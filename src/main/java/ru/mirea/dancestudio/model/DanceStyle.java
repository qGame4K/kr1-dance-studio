package ru.mirea.dancestudio.model;

/**
 * Направление танца, которое преподают в студии.
 * Это перечисление (enum) — фиксированный список допустимых значений,
 * чтобы в базе не могли появиться произвольные опечатки вроде "хипхоп" и "HipHop".
 *
 * В базе данных хранится как строка (имя константы), в консоли выбирается
 * по номеру через ConsoleInput.readEnum(...), чтобы пользователь не мог
 * ввести несуществующий стиль.
 */
public enum DanceStyle {
    /** Хип-хоп. */
    HIP_HOP,
    /** Сальса. */
    SALSA,
    /** Бачата. */
    BACHATA,
    /** Балет. */
    BALLET,
    /** Контемпорари (современный танец). */
    CONTEMPORARY,
    /** Латина (сборное направление латиноамериканских танцев). */
    LATINA,
    /** Вальс. */
    WALTZ,
    /** Джаз-фанк. */
    JAZZ_FUNK
}
