package ru.mirea.dancestudio.model;

/**
 * Уровень подготовки, на который рассчитано занятие.
 * Как и DanceStyle, зафиксирован в виде enum, чтобы значение всегда было
 * одним из трёх предсказуемых вариантов — это удобно и для хранения в БД,
 * и для фильтрации/выбора в консоли.
 */
public enum DanceLevel {
    /** Для новичков, без предварительной подготовки. */
    BEGINNER,
    /** Для тех, кто уже освоил базу. */
    INTERMEDIATE,
    /** Продвинутый уровень, для опытных танцоров. */
    ADVANCED
}
